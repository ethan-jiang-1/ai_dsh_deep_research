// docs-reference.mjs — docs/reference/*.generated.md 与 commands.md 的纯生成/新鲜度校验核。
//
// 纯 fs/path 模块（零子进程，keyless 回归可直引）：
//   - renderPackageCatalog(root)   → docs/reference/package-catalog.generated.md
//   - renderCockpitRegistry(root)  → docs/reference/cockpit-registry.generated.md
//   - renderGatesLedger(root)      → docs/reference/gates-ledger.generated.md
//   - packageCatalogProblems(root) / cockpitRegistryProblems(root) / gatesLedgerProblems(root, gates)
//   - commandsDocProblems(root)    → docs/reference/commands.md ↔ package.json scripts 双向对账
//
// 生成器入口 = tools/record/render-docs-reference.mjs（`pnpm docs:gen` / `pnpm docs:check`）。
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const AUTO_HEADER = '<!-- AUTO-GENERATED by `pnpm docs:gen` (`node tools/record/render-docs-reference.mjs`) — DO NOT EDIT MANUALLY -->'

/** 递归收集目录下匹配扩展名的相对路径（跳过 .git / node_modules / .DS_Store；不跟随目录 symlink，保留文件 symlink）。 */
function walkFiles(dir, extRe, out = []) {
  if (!existsSync(dir)) return out
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    if (ent.name === '.git' || ent.name === 'node_modules' || ent.name === '.DS_Store') continue
    const p = join(dir, ent.name)
    if (ent.isDirectory()) walkFiles(p, extRe, out)
    else if (extRe.test(ent.name)) out.push(p)
  }
  return out
}

/** 转义表格单元格并清理会误触 live 文档门禁的符号（竖线、反引号、换行）。 */
function cellText(raw, maxLen = 120) {
  const cleaned = String(raw ?? '')
    .replace(/\s+/g, ' ')
    .replace(/`/g, '')
    .replace(/\|/g, '\\|')
    .trim()
  if (cleaned === '') return '—'
  return cleaned.length > maxLen ? `${cleaned.slice(0, maxLen - 1)}…` : cleaned
}

/** 从 TS/TSX 源文件顶部注释提取首行摘要。 */
function firstCommentSummary(filePath) {
  let text = ''
  try { text = readFileSync(filePath, 'utf8') } catch { return '—' }
  const lines = text.split('\n').slice(0, 15)
  for (const raw of lines) {
    const line = raw.trim()
    if (line === '' || line.startsWith('import ') || line.startsWith('export ')) continue
    if (line.startsWith('/**') || line.startsWith('/*')) {
      const inner = line.replace(/^\/\*\*?/, '').replace(/\*\/$/, '').trim()
      if (inner) return cellText(inner, 96)
      continue
    }
    if (line.startsWith('*')) {
      const inner = line.replace(/^\*+\/?/, '').trim()
      if (inner && !inner.startsWith('@')) return cellText(inner, 96)
      continue
    }
    if (line.startsWith('//')) {
      const inner = line.replace(/^\/\/\s*/, '').trim()
      if (inner && !/^eslint|@ts-/.test(inner)) return cellText(inner, 96)
    }
  }
  return '—'
}

/** 解析单个 preset/worker patch YAML 的 id、name、description、tools 列表。 */
function parsePatchSummary(filePath) {
  const yml = readFileSync(filePath, 'utf8')
  const id = /^\s+id:\s*([a-z0-9-]+)\s*$/m.exec(yml)?.[1] ?? '—'
  const name = /^\s+name:\s*(.+?)\s*$/m.exec(yml.slice(yml.indexOf('config:')))?.[1]?.replace(/^['"]|['"]$/g, '') ?? '—'
  const desc = /^\s+description:\s*(.+?)\s*$/m.exec(yml)?.[1]?.replace(/^['"]|['"]$/g, '') ?? '—'
  const tools = [...new Set([...yml.matchAll(/name:\s*'(@deepseek-ai\/dsh-tool-[a-z0-9-]+|dsh-deep-research-pack\/[a-z0-9-]+)'/g)].map((m) => m[1]))].sort()
  return { id, name, desc, tools }
}

/** 渲染 docs/reference/package-catalog.generated.md（全量扫描 packages/deep-research-pack）。 */
export function renderPackageCatalog(root) {
  const pack = join(root, 'packages', 'deep-research-pack')
  const pkg = JSON.parse(readFileSync(join(pack, 'package.json'), 'utf8'))
  const cordisYml = readFileSync(join(pack, 'cordis.patch.yml'), 'utf8')
  const keysTs = readFileSync(join(pack, 'src', 'client', 'keys.ts'), 'utf8')

  const lines = [
    '# Package Catalog（`dsh-deep-research-pack`）',
    '',
    AUTO_HEADER,
    '',
    '> 由 `packages/deep-research-pack/` 盘上声明自动生成；严禁手改。改包清单、patch、角色或槽位后执行 `pnpm docs:gen`。',
    '',
    '## 包清单元数据',
    '',
    '| 字段 | 值 |',
    '|---|---|',
    `| 包名 | \`${pkg.name}\` |`,
    `| 版本 | \`${pkg.version}\` |`,
    `| DSH 兼容范围（\`engines.dsh\`） | \`${String(pkg.engines?.dsh ?? '—').replace(/\|/g, '\\|')}\` |`,
    `| Node 范围（\`engines.node\`） | \`${String(pkg.engines?.node ?? '—').replace(/\|/g, '\\|')}\` |`,
    `| Client 平台 | \`${pkg.dsh?.client?.platform ?? '—'}\` |`,
    `| 只读诊断 CLI（\`bin\`） | ${Object.entries(pkg.bin ?? {}).map(([k, v]) => `\`${k}\` → \`packages/deep-research-pack/${String(v).replace(/^\.\//, '')}\``).join('、') || '—'} |`,
    '',
    '## Exports',
    '',
    '| Subpath | Default / Target | Types |',
    '|---|---|---|',
  ]

  for (const [sub, spec] of Object.entries(pkg.exports ?? {})) {
    const def = typeof spec === 'string' ? spec : (spec?.default ?? '—')
    const types = typeof spec === 'object' && spec !== null && spec.types ? `\`${spec.types}\`` : '—'
    lines.push(`| \`${sub}\` | \`${def}\` | ${types} |`)
  }

  lines.push('', '## Bundle Patch 声明', '', '### `dsh.bundle.patch` 列表', '')
  for (const rel of pkg.dsh?.bundle?.patch ?? []) {
    lines.push(`- \`packages/deep-research-pack/${String(rel).replace(/^\.\//, '')}\``)
  }

  const replaceIds = [...cordisYml.matchAll(/^- id:\s*([a-z0-9-]+)\s*$/gm)].map((m) => m[1])
  const insertIds = [...cordisYml.matchAll(/^    - id:\s*([a-z0-9-]+)\s*$/gm)].map((m) => m[1])
  lines.push(
    '',
    '### `cordis.patch.yml` 行清单',
    '',
    '| 操作 | 行 ID |',
    '|---|---|',
    `| 替换 / 关闭（\`- id:\`） | ${replaceIds.map((id) => `\`${id}\``).join('、') || '—'} |`,
    `| 新增（\`- insert:\`） | ${insertIds.map((id) => `\`${id}\``).join('、') || '—'} |`,
  )

  lines.push('', '## 角色预设与 Worker Profiles', '', '| 类型 | ID | 名称 | 工具行 | Skills |', '|---|---|---|---|---|')
  const presetsDir = join(pack, 'presets')
  const presetFiles = existsSync(presetsDir)
    ? readdirSync(presetsDir).filter((f) => f.endsWith('.patch.yml')).sort()
    : []
  for (const f of presetFiles) {
    const info = parsePatchSummary(join(presetsDir, f))
    const skillsDir = join(presetsDir, info.id, 'skills')
    const skills = existsSync(skillsDir)
      ? readdirSync(skillsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
      : []
    const toolList = info.tools.map((t) => `\`${t.replace(/^@deepseek-ai\//, '')}\``).join('、') || '—'
    const skillList = skills.map((s) => `\`${s}\``).join('、') || '—'
    lines.push(`| preset | \`${info.id}\` | ${cellText(info.name, 48)} | ${toolList} | ${skillList} |`)
  }

  const workersDir = join(pack, 'workers')
  const workerFiles = existsSync(workersDir)
    ? readdirSync(workersDir).filter((f) => f.endsWith('.patch.yml')).sort()
    : []
  for (const f of workerFiles) {
    const info = parsePatchSummary(join(workersDir, f))
    const toolList = info.tools.map((t) => `\`${t.replace(/^@deepseek-ai\//, '')}\``).join('、') || '—'
    lines.push(`| worker | \`${info.id}\` | ${cellText(info.name, 48)} | ${toolList} | 按 brief 跨角色加载 |`)
  }

  lines.push('', '## Client 注入依赖（`dsh.client.inject`）', '')
  for (const dep of pkg.dsh?.client?.inject ?? []) {
    lines.push(`- \`${dep}\``)
  }

  lines.push('', '## Client Keyed 常量与槽位（`src/client/keys.ts`）', '', '| 导出常量 | 字面量值 |', '|---|---|')
  for (const m of keysTs.matchAll(/export const (\w+) = ('[^']+'|\[[^\]]+\])/g)) {
    lines.push(`| \`${m[1]}\` | \`${cellText(m[2], 96)}\` |`)
  }

  return `${lines.join('\n')}\n`
}

/** 盘上收集驾驶舱全部源码模块（src/client 与 src/lib 下的 .ts/.tsx，按 pack 相对路径排序）。 */
export function collectCockpitModules(packDir) {
  const dirs = [join(packDir, 'src', 'client'), join(packDir, 'src', 'lib')]
  const files = dirs.flatMap((d) => walkFiles(d, /\.(ts|tsx)$/))
  return files
    .map((abs) => relative(packDir, abs).split(sep).join('/'))
    .sort((a, b) => a.localeCompare(b))
}

/** 渲染 docs/reference/cockpit-registry.generated.md（研究驾驶舱全量模块注册表）。 */
export function renderCockpitRegistry(root) {
  const pack = join(root, 'packages', 'deep-research-pack')
  const modules = collectCockpitModules(pack)
  const clientMods = modules.filter((m) => m.startsWith('src/client/'))
  const libMods = modules.filter((m) => m.startsWith('src/lib/'))

  const lines = [
    '# Research Cockpit 模块注册表',
    '',
    AUTO_HEADER,
    '',
    '> 由 `packages/deep-research-pack/src/{client,lib}/` 自动扫描生成；严禁手改。增删模块后执行 `pnpm docs:gen`，由 `cockpit-doc-registry` 门禁校验新鲜度。',
    '',
    '## Client 模块（`src/client/`）',
    '',
    '| 模块路径 | 摘要（源自文件头注） |',
    '|---|---|',
  ]
  for (const mod of clientMods) {
    lines.push(`| \`${mod}\` | ${firstCommentSummary(join(pack, mod))} |`)
  }

  lines.push('', '## 折算层纯函数模块（`src/lib/`）', '', '| 模块路径 | 摘要（源自文件头注） |', '|---|---|')
  for (const mod of libMods) {
    lines.push(`| \`${mod}\` | ${firstCommentSummary(join(pack, mod))} |`)
  }

  return `${lines.join('\n')}\n`
}

/** 校验 cockpit-registry.generated.md 的完整性与新鲜度（供 cockpit-doc-registry 门禁复用）。 */
export function cockpitRegistryProblems(root) {
  const pack = join(root, 'packages', 'deep-research-pack')
  const regPath = join(root, 'docs', 'reference', 'cockpit-registry.generated.md')
  const modules = collectCockpitModules(pack)
  const problems = []
  if (modules.length === 0) {
    problems.push('src/client 与 src/lib 下 0 个 .ts/.tsx（防空集：驾驶舱 client 面与折算层常在）')
    return problems
  }
  if (!existsSync(regPath)) {
    problems.push('docs/reference/cockpit-registry.generated.md 缺席——运行 `pnpm docs:gen` 生成')
    return problems
  }
  const actual = readFileSync(regPath, 'utf8')
  for (const mod of modules) {
    if (!actual.includes(`\`${mod}\``)) {
      problems.push(`packages/deep-research-pack/${mod} 未在 docs/reference/cockpit-registry.generated.md 登记（修正 = 运行 pnpm docs:gen）`)
    }
  }
  const expected = renderCockpitRegistry(root)
  if (problems.length === 0 && actual !== expected) {
    problems.push('docs/reference/cockpit-registry.generated.md 与源码盘面漂移——运行 `pnpm docs:gen` 重生成（生成物勿手改）')
  }
  return problems
}

/** 解析 context.mjs 的 gates 数组、verify/gates/*.mjs 头注及 gates-cases.mjs 覆盖情况。 */
function parseGateSources(root) {
  const ctxSrc = readFileSync(join(root, 'checks', 'verify', 'context.mjs'), 'utf8')
  const gm = /const gates = \[([^\]]+)\]/.exec(ctxSrc)
  const gateNames = gm ? gm[1].split(',').map((s) => s.trim().replace(/^'|'$/g, '')).filter(Boolean) : []

  /** @type {Map<string, { file: string, summary: string }>} */
  const headers = new Map()
  const gatesDir = join(root, 'checks', 'verify', 'gates')
  for (const f of readdirSync(gatesDir).filter((x) => x.endsWith('.mjs')).sort()) {
    const txt = readFileSync(join(gatesDir, f), 'utf8')
    for (const m of txt.matchAll(/^(?:\/\/|\s*\*)\s*──\s*([a-z0-9-]+)（([^\n]+)/gm)) {
      const summary = m[2]
        .replace(/）\s*──\s*$/, '')
        .replace(/──\s*$/, '')
        .replace(/）\s*$/, '')
        .replace(/已销账|修订 →|曾用|首版[^\n]{0,15}已由/g, '历史条目')
        .trim()
      headers.set(m[1], { file: f, summary })
    }
  }

  const casesSrc = readFileSync(join(root, 'checks', 'lib', 'harness', 'gates-cases.mjs'), 'utf8')
  /** @type {Map<string, string[]>} */
  const casesByGate = new Map()
  const casesPart = casesSrc.slice(casesSrc.indexOf('export const CASES'), casesSrc.indexOf('export const NO_CASE_GATES'))
  for (const m of casesPart.matchAll(/\{\s*id:\s*'([^']+)'\s*,\s*gate:\s*'([^']+)'/g)) {
    const [, id, gate] = m
    if (!casesByGate.has(gate)) casesByGate.set(gate, [])
    casesByGate.get(gate)?.push(id)
  }

  /** @type {Map<string, string>} */
  const noCaseReasons = new Map()
  const noCasePart = casesSrc.slice(casesSrc.indexOf('export const NO_CASE_GATES'), casesSrc.indexOf('export const CONTROLS'))
  for (const m of noCasePart.matchAll(/\{\s*gate:\s*'([^']+)'\s*,\s*reason:\s*'([^']+)'/g)) {
    noCaseReasons.set(m[1], m[2])
  }

  return { gateNames, headers, casesByGate, noCaseReasons }
}

/** 渲染 docs/reference/gates-ledger.generated.md（全量 L0 门禁自动台账）。 */
export function renderGatesLedger(root) {
  const { gateNames, headers, casesByGate, noCaseReasons } = parseGateSources(root)
  const lines = [
    '# L0 机械门禁自动台账',
    '',
    AUTO_HEADER,
    '',
    '> 由 `checks/verify/context.mjs`、`checks/verify/gates/*.mjs` 与 `checks/lib/harness/gates-cases.mjs` 自动汇总；严禁手改。增改门禁后执行 `pnpm docs:gen`，由 `gate-ledger-sync` 校验集合与字节新鲜度。',
    '',
    '| 门禁 | 域 / 实现 | 断言摘要（源自门禁头注） | 自测覆盖（`gates.e2e` CASES / NO_CASE） |',
    '|---|---|---|---|',
  ]
  for (const gate of gateNames) {
    const meta = headers.get(gate)
    const owner = meta ? `\`checks/verify/gates/${meta.file}\`` : '—'
    const summary = meta ? cellText(meta.summary, 110) : '—'
    const caseIds = casesByGate.get(gate)
    let coverage = '—'
    if (caseIds && caseIds.length > 0) {
      const shown = caseIds.slice(0, 4).map((id) => `\`${id}\``).join('、')
      coverage = caseIds.length > 4 ? `${shown} 等` : shown
    } else if (noCaseReasons.has(gate)) {
      coverage = `NO_CASE：${cellText(noCaseReasons.get(gate), 80)}`
    }
    lines.push(`| \`${gate}\` | ${owner} | ${summary} | ${coverage} |`)
  }
  return `${lines.join('\n')}\n`
}

/** 校验 gates-ledger.generated.md 集合与新鲜度（供 gate-ledger-sync 门禁复用）。 */
export function gatesLedgerProblems(root, expectedGates) {
  const ledgerPath = join(root, 'docs', 'reference', 'gates-ledger.generated.md')
  const problems = []
  if (!existsSync(ledgerPath)) {
    problems.push('docs/reference/gates-ledger.generated.md 缺席——运行 `pnpm docs:gen` 生成')
    return problems
  }
  const actual = readFileSync(ledgerPath, 'utf8')
  const ledger = new Set()
  for (const line of actual.split('\n')) {
    const m = /^\| `([a-z0-9-]+)` \|/.exec(line)
    if (m) ledger.add(m[1])
  }
  for (const g of expectedGates) {
    if (!ledger.has(g)) problems.push(`gates-ledger.generated.md 缺门禁：${g}——运行 \`pnpm docs:gen\` 同步`)
  }
  for (const l of ledger) {
    if (!expectedGates.includes(l)) problems.push(`gates-ledger.generated.md 多出门禁（context.mjs 无此名）：${l}`)
  }
  const expected = renderGatesLedger(root)
  if (problems.length === 0 && actual !== expected) {
    problems.push('docs/reference/gates-ledger.generated.md 与门禁源码/案例表漂移——运行 `pnpm docs:gen` 重生成（生成物勿手改）')
  }
  return problems
}

/** 校验 docs/reference/package-catalog.generated.md 新鲜度。 */
export function packageCatalogProblems(root) {
  const outPath = join(root, 'docs', 'reference', 'package-catalog.generated.md')
  if (!existsSync(outPath)) {
    return ['docs/reference/package-catalog.generated.md 缺席——运行 `pnpm docs:gen` 生成']
  }
  const actual = readFileSync(outPath, 'utf8')
  const expected = renderPackageCatalog(root)
  if (actual !== expected) {
    return ['docs/reference/package-catalog.generated.md 与 pack 声明漂移——运行 `pnpm docs:gen` 重生成（生成物勿手改）']
  }
  return []
}

/** 校验 docs/reference/commands.md 与根 package.json scripts 双向一致。 */
export function commandsDocProblems(root) {
  const pkgPath = join(root, 'package.json')
  const docPath = join(root, 'docs', 'reference', 'commands.md')
  const problems = []
  if (!existsSync(docPath)) {
    problems.push('docs/reference/commands.md 缺席——pnpm 命令字典正本')
    return problems
  }
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const scripts = Object.keys(pkg.scripts ?? {}).sort()
  if (scripts.length === 0) {
    problems.push('package.json scripts 为空（防空语料）')
    return problems
  }
  const doc = readFileSync(docPath, 'utf8')
  const documented = new Set()
  for (const line of doc.split('\n')) {
    const m = /^\| `pnpm ([a-z0-9:_-]+)` \|/.exec(line)
    if (m) documented.add(m[1])
  }
  if (documented.size === 0) {
    problems.push('docs/reference/commands.md 未解析到任何 `| `pnpm <name>` |` 表格行（防空语料）')
    return problems
  }
  for (const s of scripts) {
    if (!documented.has(s)) problems.push(`docs/reference/commands.md 缺 package.json 脚本：pnpm ${s}`)
  }
  for (const d of documented) {
    if (!scripts.includes(d)) problems.push(`docs/reference/commands.md 登记了不存在的脚本：pnpm ${d}`)
  }
  return problems
}
